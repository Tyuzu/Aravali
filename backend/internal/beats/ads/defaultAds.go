// getSafeDefaultAds returns a thread-safe copy of default ads.
func getSafeDefaultAds() []Ad {
	adsMutex.RLock()
	defer adsMutex.RUnlock()

	copied := make([]Ad, len(defaultAds))
	copy(copied, defaultAds)
	return copied
}
